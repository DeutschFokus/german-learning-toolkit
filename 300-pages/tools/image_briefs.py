#!/usr/bin/env python3
"""List every illustration slot of a level as a brief for the illustrator or an image model.

    python tools/image_briefs.py --level a2 --lang en > docs/image-briefs-a2.md

For each slot: where it sits, its format and size, the chapter palette, the scene description from
the content file and the path where the finished picture goes. See docs/illustration-style-guide.md.
"""
import argparse
import re
import sys
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from pydantic import BaseModel  # noqa: E402

from engine import models as M  # noqa: E402
from engine.config import MM, load_config  # noqa: E402
from engine.loader import load_book  # noqa: E402
from engine.pipeline import Builder  # noqa: E402
from engine.render import Renderer  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--level", default="a2")
ap.add_argument("--lang", default="en")
ap.add_argument("--chapters", default=None)
a = ap.parse_args()

cfg = load_config(a.level, a.lang)
book = load_book(cfg, a.chapters)
res = Builder(cfg, book).build()
bl_mm = cfg.bl / MM
col = round(cfg.page["main"] - cfg.page["label_col"], 1)
GROW = 5                                              # lines an elastic slot may grow (10 half-lines)


def slot(fmt: str, pinned: bool = False) -> tuple[str, str, str]:
    """(size in the book, picture to deliver, what to keep in mind)"""
    if pinned and fmt in Renderer.IMAGE_LINES and fmt != "square":
        h = Renderer.IMAGE_LINES[fmt] * bl_mm
        return (f"{col:g} × {h:.0f} mm (fixed: the numbered pins are placed in per cent)", f"1400 × {round(1400 * h / col / 10) * 10} px · {col / h:.2f} : 1",
                "Exactly this shape, nothing is cropped. Draw each object under its pin and leave the pin spots free of small detail.")
    if fmt == "banner":
        return ("216 × 96 mm (full width, bleeds off three edges)", "2560 × 1140 px · 2.25 : 1",
                "The chapter numeral covers the lower left corner – keep it calm there. No faces within 8 mm of the top and side edges.")
    lines = Renderer.IMAGE_LINES[fmt]
    lo, hi = lines * bl_mm, (lines + GROW) * bl_mm
    if fmt == "square":
        return (f"{lo:.0f} × {lo:.0f} mm", "900 × 900 px · 1 : 1", "Fixed size.")
    px_w = 1400
    px_h = round(px_w * hi / col / 10) * 10
    return (f"{col:g} mm wide, {lo:.0f}–{hi:.0f} mm high (the slot grows to fill its page)", f"{px_w} × {px_h} px · {col / hi:.2f} : 1",
            f"The picture is cropped from top and bottom when the slot is lower: keep everything important in the middle {lo / hi:.0%} of the height.")


def walk(obj, found, ctx):
    if isinstance(obj, M.Image):
        found.append((obj, dict(ctx)))
    elif isinstance(obj, M.Task):
        ctx = dict(ctx, task=obj.id)
        for v in obj.__dict__.values():
            walk(v, found, ctx)
    elif isinstance(obj, BaseModel):
        for v in obj.__dict__.values():
            walk(v, found, ctx)
    elif isinstance(obj, (list, tuple)):
        for v in obj:
            walk(v, found, ctx)


page_of = {}
for s in res.pages:
    for iid in re.findall(r'id="img-([^"]+)"', s.inner):
        page_of.setdefault(iid, s.label)

print(f"# Image briefs · {cfg.level_name}\n")
print("Generated by `python tools/image_briefs.py` from the content files – do not edit by hand.")
print("Style, characters and prompt template: [illustration-style-guide.md](illustration-style-guide.md).\n")
total = 0
for part in book.parts():
    is_ch = isinstance(part, M.Chapter)
    tokens = cfg.chapter_tokens(part.number) if is_ch else cfg.station_tokens()
    title = f"Kapitel {part.number} · {part.title}" if is_ch else part.title
    print(f"## {title}\n")
    print("Palette: " + " · ".join(f"{k} `{tokens[k]}`" for k in ("mid", "hl", "soft", "wash", "deep")) + "\n")
    found = []
    if is_ch:
        found.append((part.image.model_copy(update={"format": "banner"}), {"teil": "Auftakt"}))
    for teil in part.teile:
        walk(teil.blocks, found, {"teil": f"Teil {teil.nr} · {teil.title}", "nr": teil.nr})
    for im, ctx in found:
        total += 1
        size, deliver, note = slot(im.format, bool(im.markers))
        where = ctx["teil"]
        if ctx.get("task"):
            where += f' · Aufgabe {part.key}.{ctx["nr"]}{ctx["task"]}'
        print(f"### `{im.id}` · page {page_of.get(im.id, '?')}\n")
        print(f"- **Where:** {where}")
        print(f"- **Format:** {im.format} – {size}")
        print(f"- **Deliver:** {deliver}, JPEG, sRGB → `assets/images/{cfg.level}/{im.id}.jpg`")
        print(f"- **Scene:** {im.description}")
        if im.alt:
            print(f"- **Alt text ({cfg.lang}):** {cfg.t(im.alt)}")
        if im.markers:
            print("- **Numbered pins** (x %, y % from the top left – the object must sit under its pin): " +
                  ", ".join(f"{m.n} ({m.x:g}, {m.y:g})" for m in im.markers))
        print(f"- **Note:** {note}")
        print(f"- **In the content file:** add `src: assets/images/{cfg.level}/{im.id}.jpg` to this image.\n")
print(f"---\n\n{total} pictures in this build.")
